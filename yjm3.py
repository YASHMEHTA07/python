
num1 = int(input("Enter First Number: "))
num2 = int(input("Enter Second Number: "))
bool1 = True
bool2 = False

print("--- 1. ARITHMETIC OPERATIONS ---")
print(f"Addition ({num1} + {num2})         = {num1 + num2}")
print(f"Subtraction ({num1} - {num2})      = {num1 - num2}")
print(f"Multiplication ({num1} * {num2})   = {num1 * num2}")
print(f"Float Division ({num1} / {num2})   = {num1 / num2}")
print(f"Floor Division ({num1} // {num2})  = {num1 // num2}")
print(f"Modulus/Remainder ({num1} % {num2}) = {num1 % num2}")
print(f"Exponentiation ({num1} ** {num2})  = {num1 ** num2}\n")

print("--- 2. LOGICAL OPERATIONS ---")
print(f"Logical AND ({bool1} and {bool2}) = {bool1 and bool2}")
print(f"Logical OR  ({bool1} or {bool2})  = {bool1 or bool2}")
print(f"Logical NOT (not {bool1})       = {not bool1}")
print(f"Logical NOT (not {bool2})       = {not bool2}\n")

