#Write a program to perform mathematical operations using math module.

import math

num = float(input("Enter a number: "))

print("Square root:", math.sqrt(num))
print("Power (num^2):", math.pow(num, 2))
print("Sine (in radians):", math.sin(num))
print("Cosine (in radians):", math.cos(num))
print("Log base 10:", math.log10(num))
print("Pi value:", math.pi)

